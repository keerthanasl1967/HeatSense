"""
Inference and prediction pipeline for HeatSense Bengaluru.

Provides:
- Input validation against physically realistic meteorological ranges.
- Dual-path inference: classical (Logistic Regression, Random Forest)
  and quantum (QSVC / VQC).
- Transparent probability / confidence scoring.
- Side-by-side comparative diagnostics.
- Non-diagnostic research disclaimers.
"""

from typing import Any, Dict, List, Optional, Tuple

import numpy as np
from src.classical_models import ClassicalModelTrainer
from src.preprocessing import PreprocessingPipeline
from src.quantum_models import QuantumClassifierTrainer


# Realistic meteorological ranges for Bengaluru urban microclimate
VALIDATION_RANGES = {
    "temperature_2m": (5.0, 50.0, "°C"),
    "relative_humidity_2m": (5.0, 100.0, "%"),
    "wind_speed_10m": (0.0, 100.0, "km/h"),
    "surface_solar_radiation": (0.0, 1400.0, "W/m²"),
}

RESEARCH_DISCLAIMER = (
    "NOTICE: Predictions generated by HeatSense Bengaluru represent experimental meteorological "
    "risk classifications based on microclimate variables. These outputs are intended for "
    "urban climate planning and comparative ML/QML research, NOT as emergency medical advisories, "
    "clinical diagnoses, or official municipal evacuation orders."
)


def validate_prediction_inputs(inputs: Dict[str, float]) -> Tuple[bool, List[str]]:
    """
    Validates user weather inputs against realistic meteorological ranges.
    Returns (is_valid, list_of_error_strings).
    """
    errors = []
    for var, (low, high, unit) in VALIDATION_RANGES.items():
        if var in inputs:
            val = inputs[var]
            if val is None or np.isnan(val):
                errors.append(f"Measurement for '{var}' is missing or NaN.")
            elif val < low or val > high:
                errors.append(
                    f"'{var}' value {val:.1f} {unit} is outside physically realistic range [{low}, {high} {unit}]."
                )
    return (len(errors) == 0), errors


class PredictionService:
    """
    Manages live multi-model prediction workflows with loaded preprocessors
    and trained classical / quantum models.
    """

    def __init__(
        self,
        preprocessor: PreprocessingPipeline,
        classical_models: Optional[Dict[str, ClassicalModelTrainer]] = None,
        quantum_model: Optional[QuantumClassifierTrainer] = None,
    ):
        self.preprocessor = preprocessor
        self.classical_models = classical_models or {}
        self.quantum_model = quantum_model

    def predict(
        self, input_measurements: Dict[str, float]
    ) -> Dict[str, Any]:
        """
        Executes unified prediction across all available models.
        """
        is_valid, errors = validate_prediction_inputs(input_measurements)
        if not is_valid:
            return {
                "success": False,
                "errors": errors,
                "disclaimer": RESEARCH_DISCLAIMER,
                "predictions": {},
            }

        # Transform inputs using fitted preprocessor
        x_classical, x_quantum = self.preprocessor.transform_single_input(input_measurements)
        class_names = self.preprocessor.classes_

        results: Dict[str, Any] = {}

        # 1. Classical Models
        for name, trainer in self.classical_models.items():
            if trainer and trainer.is_trained:
                pred_idx, latency = trainer.predict(x_classical)
                pred_label = class_names[pred_idx[0]]
                proba = trainer.predict_proba(x_classical)
                proba_dict = (
                    {class_names[i]: float(p) for i, p in enumerate(proba[0])}
                    if proba is not None
                    else None
                )

                results[name] = {
                    "model_family": "Classical",
                    "predicted_category": pred_label,
                    "confidence_distribution": proba_dict,
                    "latency_ms": round(latency * 1000.0, 3),
                    "status": "Success",
                }
            else:
                results[name] = {
                    "model_family": "Classical",
                    "status": "Model not trained yet",
                }

        # 2. Quantum Model
        if self.quantum_model and self.quantum_model.is_trained:
            try:
                import time
                t0 = time.perf_counter()
                q_pred_idx = self.quantum_model.predict_single(x_quantum)
                q_latency = time.perf_counter() - t0
                q_label = class_names[q_pred_idx] if q_pred_idx < len(class_names) else f"Class {q_pred_idx}"

                results["quantum_qsvc"] = {
                    "model_family": "Quantum (Qiskit)",
                    "predicted_category": q_label,
                    "confidence_distribution": None,  # Kernel SVM does not give direct soft probabilities
                    "latency_ms": round(q_latency * 1000.0, 3),
                    "circuit_qubits": self.quantum_model.num_qubits,
                    "status": "Success",
                }
            except Exception as e:
                results["quantum_qsvc"] = {
                    "model_family": "Quantum (Qiskit)",
                    "status": f"Simulation Error: {str(e)}",
                }
        else:
            results["quantum_qsvc"] = {
                "model_family": "Quantum (Qiskit)",
                "status": "Quantum model not trained yet",
            }

        return {
            "success": True,
            "inputs": input_measurements,
            "predictions": results,
            "disclaimer": RESEARCH_DISCLAIMER,
        }
